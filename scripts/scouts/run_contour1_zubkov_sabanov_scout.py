def calculate_anti_homonym_score(
    has_exact_village: bool,
    has_exact_uyezd_rvk: bool,
    has_sabanov_cross_tie: bool,
    has_kumanin_cross_tie: bool,
    has_chronological_fit_1895_1922: bool,
    has_patronymic_continuity: bool,
    penalty_points: int = 0
) -> Dict[str, Any]:
    """
    100-балльная шкала защиты от однофамильцев (Anti-Homonym Scoring Matrix v2.0
    из раздела 5 SEARCH_MASTER_ROADMAP.md).
    """
    geo_score = 0
    if has_exact_village:
        geo_score = 35
    elif has_exact_uyezd_rvk:
        geo_score = 20

    cross_kin_score = 0
    if has_sabanov_cross_tie and has_kumanin_cross_tie:
        cross_kin_score = 25
    elif has_sabanov_cross_tie or has_kumanin_cross_tie:
        cross_kin_score = 22

    chrono_score = 20 if has_chronological_fit_1895_1922 else 10
    patronymic_score = 20 if has_patronymic_continuity else 12

    total = max(0, min(100, geo_score + cross_kin_score + chrono_score + patronymic_score - penalty_points))
    if total >= 85:
        tier = "P0_PRIME_ARCHIVE_CANDIDATE"
    elif total >= 65:
        tier = "P1_HIGH_PROBABILITY_CANDIDATE"
    else:
        tier = "P2_SECONDARY_HOMONYM_CHECK"

    return {
        "total_score": total,
        "tier": tier,
        "breakdown": {
            "geography_max_35": geo_score,
            "cross_clan_tie_max_25": cross_kin_score,
            "chronology_max_20": chrono_score,
            "patronymic_tradition_max_20": patronymic_score,
            "penalty": -penalty_points
        }
    }


